// Writes the long play scripts in tests/native/ from a plan the rules
// confirm: tests/native/journey-first-stage.play plays Journey stage 1
// ("First Shift", earn 500 credits) from the title to its results by keys —
// L1 selected, then every second of play Hire, Assign, Lift capacity, Lift
// speed and Shaft (a command the credits cannot pay is refused, as in the
// game). The rules simulate the same policy at the runtime's 60 steps a
// second to check it finishes and to size the wait.
//   node tools/gen-plays.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const R = require('../js/rules.js');
const C = require('../js/content.js');

const POLICY = [['KeyH', 'hire'], ['Enter', 'assign'], ['KeyW', 'upgrade_lift_cap'], ['KeyE', 'upgrade_lift_speed'], ['KeyQ', 'upgrade_shaft']];
// Simulate: one command a frame for POLICY.length frames, then wait the rest of 60 frames.
const st = C.buildState(C.JOURNEY[0]);
let carry = 0, frames = 0;
const step = () => { carry += 1000 / 60; const ms = Math.floor(carry); carry -= ms; R.advance(st, ms); frames++; };
while (!st.terminal && frames < 60 * 600) {
  for (const [, type] of POLICY) { R.applyCommand(st, { type, layer: 0 }); step(); }
  for (let i = POLICY.length; i < 60; i++) step();
}
if (!st.terminal || !st.terminal.won) throw new Error('the plan does not finish stage 1');
// Stop a few seconds early: the shift finishes on its own, and no key may land on the results.
const cycles = Math.floor(frames / 60) - 5;
const lines = [
  '# Generated by tools/gen-plays.mjs: Journey stage 1 ("First Shift") from the title to its',
  `# results by keys (the rules finish it in ${Math.round(frames / 60)} s of play with this plan).`,
  'until 300 Daily Vein',
  'frames 30',
  'click Journey',
  'until 60 stages complete',
  'frames 10',
  'click Stage 1 First Shift',
  'until 60 Start shift',
  'expect Assign workers, hire when you can.',
  'frames 5',
  'click =Start shift',
  'until 200 Earn 500 credits',
  'frames 130',
  'save journey-countdown-over',
  'key ArrowDown 1',
  'frames 3',
];
for (let c = 0; c < cycles; c++) {
  for (const [key] of POLICY) lines.push(`key ${key} 1`);
  lines.push('frames 53'); // a key line takes a frame, frames N takes N+1: 60 a cycle
  if (c === 30) lines.push('save journey-mid');
}
lines.push('until 3600 Objective complete', 'frames 30', 'expect final score', 'save journey-results', 'key Tab 1', 'frames 5', 'key Tab 1', 'frames 5', 'save journey-results-buttons', 'key Enter 1', 'until 120 Daily Vein', 'expect (1/40)');
writeFileSync(join(root, 'tests/native/journey-first-stage.play'), lines.join('\n') + '\n');
console.log(`journey-first-stage.play: ${cycles} cycles (rules: ${frames} frames)`);
